/**
 * Render `osv-scanner.toml` from the OpenVEX ledger, because osv-scanner cannot read VEX.
 *
 * grype and trivy both take `--vex` and honor `not_affected` directly (probed 2026-08-18: grype
 * 0.111.1 moved extract-zip's two matches into `ignoredMatches` with
 * `{namespace: "vex", vex-status: "not_affected"}`). osv-scanner 2.5.0 has no VEX flag at all — its
 * only suppression surface is `[[IgnoredVulns]]` in its own TOML. Rendering that file from the
 * ledger keeps ONE record of why a finding is suppressed: a second hand-maintained list is how a
 * suppression outlives the reasoning that justified it.
 *
 * The generated file is committed, and `tests-integration/tests/vex.test.ts` fails when it drifts
 * from this script's output — the same shape as the AGENTS.md and README-figures drift gates, and for
 * the same reason: a generated artifact nobody regenerates is worse than no artifact, because it
 * looks current.
 *
 * Only `not_affected` and `fixed` render an ignore entry. `affected` and `under_investigation` are
 * deliberately dropped: those statuses say a finding is real or unresolved, and suppressing them
 * would invert the ledger's meaning.
 *
 *   node scripts/vex-to-osv-config.mjs                  rewrite osv-scanner.toml in place
 *   node scripts/vex-to-osv-config.mjs --check          exit 1 if the committed file is stale
 *   node scripts/vex-to-osv-config.mjs --stdout [vex]   render to stdout, from an alternate ledger
 */
import { readFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
export const VEX_PATH = join(REPO_ROOT, "security", "memhtml.openvex.json")
export const OSV_CONFIG_PATH = join(REPO_ROOT, "osv-scanner.toml")

/** Statuses that justify suppressing a finding. See the module docstring for why the other two do not. */
const SUPPRESSING = new Set(["not_affected", "fixed"])

/**
 * A TOML multi-line literal string performs NO escape processing, so it cannot be broken by the
 * quotes, backslashes, and backticks an impact statement naturally contains. The only sequence it
 * cannot hold is its own delimiter, which is therefore refused rather than mangled.
 */
const literal = (text) => {
  if (text.includes("'''")) {
    throw new Error("a VEX impact_statement cannot contain ''' — it is the TOML literal delimiter")
  }
  return `'''\n${text}\n'''`
}

export const renderOsvConfig = (vex) => {
  const lines = [
    "# GENERATED by scripts/vex-to-osv-config.mjs from security/memhtml.openvex.json — do not edit.",
    "#",
    "# osv-scanner 2.5.0 has no --vex flag, so the OpenVEX ledger is rendered into the one",
    "# suppression surface it does have. Change security/memhtml.openvex.json and run",
    "# `mise run security:vex`; tests-integration/tests/vex.test.ts fails if this file drifts.",
    ""
  ]

  for (const statement of vex.statements) {
    if (!SUPPRESSING.has(statement.status)) continue
    // Every alias too: a scanner keys on whichever id its database happens to use, and an ignore
    // that names only the GHSA silently stops applying the day one of them reports the CVE.
    const ids = [statement.vulnerability.name, ...(statement.vulnerability.aliases ?? [])]
    const reason = [
      `${statement.status}: ${statement.justification ?? "no justification recorded"}`,
      "",
      statement.impact_statement ?? "",
      "",
      "Recorded in security/memhtml.openvex.json (OpenVEX). Do not edit this file directly."
    ]
      .join("\n")
      .trim()

    for (const id of ids) {
      lines.push("[[IgnoredVulns]]", `id = ${JSON.stringify(id)}`, `reason = ${literal(reason)}`, "")
    }
  }

  return `${lines.join("\n").trimEnd()}\n`
}

export const readVex = (path = VEX_PATH) => JSON.parse(readFileSync(path, "utf8"))

const argv = process.argv.slice(2)
const flag = (name) => argv.includes(name)
/** The positional after `--stdout`, so a test can render a synthetic ledger without writing to the repo. */
const ledgerPath = argv.find((arg) => !arg.startsWith("--")) ?? VEX_PATH

const rendered = renderOsvConfig(readVex(ledgerPath))
const entries = (rendered.match(/\[\[IgnoredVulns\]\]/g) ?? []).length

if (flag("--stdout")) {
  process.stdout.write(rendered)
} else if (flag("--check")) {
  const committed = readFileSync(OSV_CONFIG_PATH, "utf8")
  if (committed === rendered) {
    console.log(`osv-scanner.toml up to date: ${entries} ignore entr${entries === 1 ? "y" : "ies"}`)
  } else {
    console.error(
      "osv-scanner.toml is STALE against security/memhtml.openvex.json.\n" +
        "Run `mise run security:vex` and commit the result."
    )
    process.exit(1)
  }
} else {
  const { writeFileSync } = await import("node:fs")
  writeFileSync(OSV_CONFIG_PATH, rendered)
  console.log(`osv-scanner.toml written: ${entries} ignore entr${entries === 1 ? "y" : "ies"}`)
}
